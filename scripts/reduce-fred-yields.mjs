/**
 * Reduce FRED Treasury yield series → src/data/generated/bond-yields.ts
 *
 * Grounds the Bonds & Interest-Rate Risk tool in real data: the current Treasury
 * yield curve across maturities, the long run of the 10-year yield, and the
 * nominal / real (TIPS) / breakeven-inflation trio at the 10-year point.
 *
 * Run:  npm run data:bond-yields
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { parseFred } from "./lib/parse-fred.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const FRED = join(root, "data", "sources", "fred");
const OUT = join(root, "src", "data", "generated", "bond-yields.ts");

const round = (x, dp = 2) => Math.round(x * 10 ** dp) / 10 ** dp;

/** Last row with a real value. */
function latest(id) {
  const { rows } = parseFred(join(FRED, `${id}.csv`));
  for (let i = rows.length - 1; i >= 0; i--) if (rows[i].value != null) return rows[i];
  return null;
}

/** Monthly rows → annual mean series [{year, yield}]. */
function annual(id) {
  const { rows } = parseFred(join(FRED, `${id}.csv`));
  const byYear = new Map();
  for (const r of rows) {
    if (r.value == null) continue;
    const y = +r.date.slice(0, 4);
    (byYear.get(y) ?? byYear.set(y, []).get(y)).push(r.value);
  }
  return [...byYear.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([year, vals]) => ({ year, yield: round(vals.reduce((s, v) => s + v, 0) / vals.length) }));
}

const CURVE = [
  { id: "TB3MS", label: "3-mo", years: 0.25 },
  { id: "GS1", label: "1-yr", years: 1 },
  { id: "GS2", label: "2-yr", years: 2 },
  { id: "GS5", label: "5-yr", years: 5 },
  { id: "GS10", label: "10-yr", years: 10 },
  { id: "GS20", label: "20-yr", years: 20 },
  { id: "GS30", label: "30-yr", years: 30 },
];

function main() {
  const curve = CURVE.map(({ id, label, years }) => {
    const r = latest(id);
    return { label, years, yield: r ? round(r.value) : null, asOf: r?.date ?? null };
  }).filter((p) => p.yield != null);

  const asOf = curve.reduce((a, p) => (p.asOf > a ? p.asOf : a), curve[0].asOf);

  const nominal10 = latest("GS10");
  const real10 = latest("DFII10");
  const breakeven10 = latest("T10YIE");

  const gs10History = annual("GS10");

  const out = `// AUTO-GENERATED by scripts/reduce-fred-yields.mjs — DO NOT EDIT.
// Re-run: npm run data:bond-yields
//
// Treasury yields from FRED: the current yield curve across maturities, the
// annual 10-year yield since 1953, and the nominal / real (TIPS) / breakeven
// trio at the 10-year point. Yields are percent per year.

export interface YieldPoint {
  label: string;
  /** Maturity in years. */
  years: number;
  /** Yield, percent per year. */
  yield: number;
}

export interface BondYields {
  source: string;
  asOf: string;
  /** Today's Treasury yield curve, short to long. */
  curve: YieldPoint[];
  /** 10-year point, decomposed. */
  tenYear: { nominal: number; real: number; breakeven: number };
  /** Annual-average 10-year yield, for the long-run context chart. */
  gs10History: { year: number; yield: number }[];
}

export const bondYields: BondYields = {
  source: "Federal Reserve Economic Data (FRED), St. Louis Fed.",
  asOf: ${JSON.stringify(asOf)},
  curve: ${JSON.stringify(curve.map(({ label, years, yield: y }) => ({ label, years, yield: y })))},
  tenYear: {
    nominal: ${round(nominal10.value)},
    real: ${round(real10.value)},
    breakeven: ${round(breakeven10.value)},
  },
  gs10History: ${JSON.stringify(gs10History)},
};
`;
  writeFileSync(OUT, out);
  console.log(`Wrote ${OUT}`);
  console.log(`  curve asOf ${asOf}: ${curve.map((p) => `${p.label} ${p.yield}%`).join(", ")}`);
  console.log(`  10yr: nominal ${round(nominal10.value)}% = real ${round(real10.value)}% + breakeven ${round(breakeven10.value)}%`);
  console.log(`  GS10 history: ${gs10History.length} years (${gs10History[0].year}–${gs10History[gs10History.length - 1].year})`);
}

main();
