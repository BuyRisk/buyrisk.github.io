/**
 * Reduce Damodaran annual returns → src/data/generated/asset-stats.ts
 *
 * Real per-asset statistics for the Portfolio Lab's "Historical" mode: the
 * annualized mean return, volatility, and the full PAIRWISE correlation matrix
 * across asset classes — computed from Aswath Damodaran's annual series
 * (1928–present), replacing the hand-set illustrative presets and the
 * single-market-factor correlation approximation.
 *
 * Damodaran "Returns by year" nominal columns → preset asset ids:
 *   1 S&P 500 → us-stocks   2 US Small cap → small-cap-value   3 T-Bill → tbills
 *   4 T-Bond → treasuries   5 Baa Corp → corporate-bonds   6 Real Estate → reits
 *   7 Gold → gold
 * (International stocks aren't in this US dataset, so they keep their illustrative
 *  preset and fall back to the market-factor correlation.)
 *
 * Run:  npm run data:assets
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readWorkbook } from "./lib/read-xlsx.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "data", "sources", "damodaran", "histretSP.xls");
const OUT = join(root, "src", "data", "generated", "asset-stats.ts");

// column index in "Returns by year" → asset id (order defines matrix order)
const COLS = [
  { col: 1, id: "us-stocks" },
  { col: 2, id: "small-cap-value" },
  { col: 6, id: "reits" },
  { col: 5, id: "corporate-bonds" },
  { col: 4, id: "treasuries" },
  { col: 3, id: "tbills" },
  { col: 7, id: "gold" },
];

const round = (x, dp) => Math.round(x * 10 ** dp) / 10 ** dp;
const mean = (a) => a.reduce((s, v) => s + v, 0) / a.length;
const std = (a) => {
  const m = mean(a);
  return Math.sqrt(a.reduce((s, v) => s + (v - m) ** 2, 0) / (a.length - 1));
};
const corr = (a, b) => {
  const ma = mean(a), mb = mean(b);
  let cov = 0, va = 0, vb = 0;
  for (let i = 0; i < a.length; i++) {
    cov += (a[i] - ma) * (b[i] - mb);
    va += (a[i] - ma) ** 2;
    vb += (b[i] - mb) ** 2;
  }
  return cov / Math.sqrt(va * vb);
};

function main() {
  const rows = readWorkbook(SRC).sheet("Returns by year");
  const h = rows.findIndex((r) => String((r || [])[0] ?? "").trim().toLowerCase() === "year");

  // Collect rows where every asset column is present, to keep one common sample.
  const series = COLS.map(() => []);
  const years = [];
  for (let i = h + 1; i < rows.length; i++) {
    const r = rows[i] || [];
    const year = Number(r[0]);
    if (!Number.isInteger(year) || year < 1900 || year > 2100) continue;
    const vals = COLS.map((c) => Number(r[c.col]));
    if (vals.some((v) => !Number.isFinite(v))) continue;
    years.push(year);
    vals.forEach((v, j) => series[j].push(v));
  }
  if (!years.length) throw new Error("no rows parsed");

  const assets = {};
  COLS.forEach((c, j) => {
    assets[c.id] = { mu: round(mean(series[j]), 4), sigma: round(std(series[j]), 4) };
  });

  const ids = COLS.map((c) => c.id);
  const correlation = {};
  ids.forEach((idA, a) => {
    correlation[idA] = {};
    ids.forEach((idB, b) => {
      correlation[idA][idB] = a === b ? 1 : round(corr(series[a], series[b]), 3);
    });
  });

  const out = {
    asOf: years[years.length - 1],
    source: "Aswath Damodaran, Historical Returns on Stocks, Bonds and Bills (NYU Stern).",
    span: [years[0], years[years.length - 1]],
    note: "Annualized nominal mean, volatility, and pairwise correlations of annual returns.",
    ids,
    assets,
    correlation,
  };
  writeFileSync(OUT, render(out));
  console.log(
    `asset-stats: ${ids.length} assets, ${years[0]}–${years[years.length - 1]} (${years.length} yrs)\n` +
      `  us-stocks μ ${(assets["us-stocks"].mu * 100).toFixed(1)}% σ ${(assets["us-stocks"].sigma * 100).toFixed(1)}%\n` +
      `  stocks↔treasuries corr ${correlation["us-stocks"]["treasuries"]}, stocks↔gold ${correlation["us-stocks"]["gold"]}\n  → ${OUT}`
  );
}

function render(o) {
  return `// AUTO-GENERATED by scripts/reduce-asset-stats.mjs — DO NOT EDIT.
// Re-run: npm run data:assets
//
// Real asset-class statistics for the Portfolio Lab "Historical" mode: annualized
// nominal mean return, volatility, and the pairwise correlation matrix, from
// Damodaran's annual US series. (International stocks aren't in this dataset.)

export interface AssetStat { mu: number; sigma: number; }

export interface AssetStats {
  asOf: number;
  source: string;
  span: [number, number];
  note: string;
  ids: string[];
  assets: Record<string, AssetStat>;
  /** correlation[a][b] = Pearson correlation of annual returns. */
  correlation: Record<string, Record<string, number>>;
}

export const assetStats: AssetStats = ${JSON.stringify(o, null, 2)};
`;
}

main();
