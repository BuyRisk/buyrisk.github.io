/**
 * Reduce Fama–French daily factors → src/data/generated/market-daily.ts
 *
 * A daily series of total returns on the whole US stock market (value-weighted,
 * dividends included) — the fuel for the "best days" version of the time-in-the-
 * market tool. Market total return = Mkt-RF + RF (the excess market return plus
 * the risk-free rate). These are NOMINAL, which is how the famous "missing the
 * best days" statistics are always presented.
 *
 * We ship from 1990 to keep the payload reasonable while still covering the
 * dot-com bust, 2008, and 2020 — the crashes where the best and worst days sit
 * right on top of each other. Run:  npm run data:market-daily
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { parseFrench, toColumns } from "./lib/parse-french.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "data", "sources", "french", "F-F_Research_Data_Factors_daily.csv");
const OUT = join(root, "src", "data", "generated", "market-daily.ts");

const FROM = 19900101;

function main() {
  const blocks = parseFrench(readFileSync(SRC, "utf8"));
  const daily = blocks.find((b) => b.frequency === "daily-or-weekly" && b.columns.includes("Mkt-RF"));
  const { period, series } = toColumns(daily);

  const returns = [];
  const dates = [];
  for (let i = 0; i < period.length; i++) {
    if (+period[i] < FROM) continue;
    const mkt = series["Mkt-RF"][i];
    const rf = series["RF"][i];
    if (mkt === null || rf === null) continue;
    returns.push(Math.round((mkt + rf) * 1e4) / 1e6); // percent → decimal, 6dp
    dates.push(period[i]);
  }

  // First return index of each calendar year, for calendar-accurate windows.
  const yearStart = {};
  for (let i = 0; i < dates.length; i++) {
    const y = +dates[i].slice(0, 4);
    if (yearStart[y] === undefined) yearStart[y] = i;
  }
  const fmt = (p) => `${p.slice(0, 4)}-${p.slice(4, 6)}-${p.slice(6, 8)}`;

  const growth = returns.reduce((g, r) => g * (1 + r), 1);
  const cagr = Math.pow(growth, 252 / returns.length) - 1;

  const out = {
    source: "Kenneth R. French Data Library, Fama–French daily research factors (Mkt-RF + RF).",
    citation: "Fama, E. F., & French, K. R. — daily value-weighted US market total return.",
    startDate: fmt(dates[0]),
    endDate: fmt(dates[dates.length - 1]),
    yearStart,
    returns,
  };
  writeFileSync(OUT, render(out));

  console.log(
    `market-daily: ${returns.length} trading days, ${out.startDate}–${out.endDate}\n` +
      `  nominal total return ≈ ${(cagr * 100).toFixed(2)}%/yr\n  → ${OUT}`
  );
}

function render(o) {
  const nums = o.returns.map(String);
  const lines = [];
  for (let i = 0; i < nums.length; i += 15) lines.push("    " + nums.slice(i, i + 15).join(", ") + ",");
  const yearStartEntries = Object.entries(o.yearStart).map(([y, i]) => `${y}: ${i}`).join(", ");

  return `// AUTO-GENERATED by scripts/reduce-french-daily.mjs — DO NOT EDIT.
// Re-run: npm run data:market-daily
//
// Daily total returns on the whole US stock market (value-weighted, dividends
// included, NOMINAL), from the Fama–French daily research factors (Mkt-RF + RF).
// \`returns[i]\` is the total return for trading day i; \`yearStart[year]\` is the
// index of that year's first trading day.

export interface MarketDaily {
  source: string;
  citation: string;
  /** These are nominal (not inflation-adjusted). */
  startDate: string;
  endDate: string;
  yearStart: Record<number, number>;
  /** Daily market total returns (decimals), consecutive from startDate. */
  returns: number[];
}

export const marketDaily: MarketDaily = {
  source: ${JSON.stringify(o.source)},
  citation: ${JSON.stringify(o.citation)},
  startDate: ${JSON.stringify(o.startDate)},
  endDate: ${JSON.stringify(o.endDate)},
  yearStart: { ${yearStartEntries} },
  returns: [
${lines.join("\n")}
  ],
};
`;
}

main();
