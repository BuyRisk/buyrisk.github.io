/**
 * Reduce data/sources/damodaran/histretSP.xls → src/data/generated/historical-returns.ts
 *
 * A clean annual panel of US nominal total returns — stocks (S&P 500 incl.
 * dividends), 3-month T-bills, 10-year T-bonds — and inflation, 1928–present.
 * This is the fuel for the tools' "Historical" (block-bootstrap) modes: real,
 * lumpy, fat-tailed return sequences instead of a smooth assumed average.
 *
 * Source sheet "Returns by year": header at the first row whose col 0 is "Year",
 * then one row per year. Columns used (0-indexed): 0 year, 1 S&P 500, 3 T-bill,
 * 4 T-bond, 20 inflation — all decimals (0.438 = +43.8%).
 *
 * Run:  npm run data:historical
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readWorkbook } from "./lib/read-xlsx.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "data", "sources", "damodaran", "histretSP.xls");
const OUT = join(root, "src", "data", "generated", "historical-returns.ts");

const round = (x, dp = 6) => {
  if (x === null || x === undefined || !Number.isFinite(+x)) return null;
  const f = 10 ** dp;
  return Math.round(+x * f) / f;
};

function main() {
  const rows = readWorkbook(SRC).sheet("Returns by year");
  const h = rows.findIndex((r) => String((r || [])[0] ?? "").trim().toLowerCase() === "year");
  if (h < 0) throw new Error("Could not find the 'Year' header row");

  const series = [];
  for (let i = h + 1; i < rows.length; i++) {
    const r = rows[i] || [];
    const year = Number(r[0]);
    if (!Number.isInteger(year) || year < 1900 || year > 2100) continue;
    const rec = {
      year,
      stocks: round(r[1]),
      tbills: round(r[3]),
      tbonds: round(r[4]),
      inflation: round(r[20]),
    };
    // Only keep fully-populated years (all four series present).
    if ([rec.stocks, rec.tbills, rec.tbonds, rec.inflation].every((v) => v !== null)) {
      series.push(rec);
    }
  }
  if (!series.length) throw new Error("No data rows parsed");

  const span = [series[0].year, series[series.length - 1].year];
  const out = {
    source: "Aswath Damodaran, Historical Returns on Stocks, Bonds and Bills (NYU Stern).",
    citation: "Damodaran, A., NYU Stern — histretSP.xls, sheet 'Returns by year'.",
    asOf: new Date().getFullYear(), // placeholder; Date is fine in a build script
    span,
    note: "Annual US NOMINAL total returns (decimals). Real return = (1+nominal)/(1+inflation)-1.",
    series,
  };
  // Date.now() etc. are allowed here (plain build script), but keep asOf stable:
  out.asOf = span[1];

  writeFileSync(OUT, render(out));
  console.log(
    `historical-returns: ${series.length} years ${span[0]}–${span[1]}\n` +
      `  e.g. ${span[1]}: stocks ${(series[series.length - 1].stocks * 100).toFixed(1)}%, ` +
      `bonds ${(series[series.length - 1].tbonds * 100).toFixed(1)}%, ` +
      `infl ${(series[series.length - 1].inflation * 100).toFixed(1)}%\n  → ${OUT}`
  );
}

function render(o) {
  const rows = o.series
    .map(
      (r) =>
        `  { year: ${r.year}, stocks: ${r.stocks}, tbills: ${r.tbills}, tbonds: ${r.tbonds}, inflation: ${r.inflation} },`
    )
    .join("\n");
  return `// AUTO-GENERATED by scripts/reduce-damodaran-returns.mjs — DO NOT EDIT.
// Re-run: npm run data:historical
//
// Annual US NOMINAL total returns (decimals) + inflation, from Aswath Damodaran's
// long-run dataset. The fuel for the tools' block-bootstrap "Historical" modes.

export interface HistoricalYear {
  year: number;
  /** S&P 500 total return (incl. dividends), nominal. */
  stocks: number;
  /** 3-month U.S. Treasury bill return, nominal. */
  tbills: number;
  /** 10-year U.S. Treasury bond return, nominal. */
  tbonds: number;
  /** Inflation (CPI) for the year. */
  inflation: number;
}

export interface HistoricalReturns {
  source: string;
  citation: string;
  asOf: number;
  span: [number, number];
  note: string;
  series: HistoricalYear[];
}

export const historicalReturns: HistoricalReturns = {
  source: ${JSON.stringify(o.source)},
  citation: ${JSON.stringify(o.citation)},
  asOf: ${o.asOf},
  span: [${o.span[0]}, ${o.span[1]}],
  note: ${JSON.stringify(o.note)},
  series: [
${rows}
  ],
};
`;
}

main();
