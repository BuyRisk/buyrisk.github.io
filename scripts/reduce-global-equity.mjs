/**
 * Reduce Fama–French regional 5-factor files → src/data/generated/global-equity.ts
 *
 * Annualized NOMINAL market total return (Mkt-RF + RF) and volatility for broad,
 * diversified equity by region — US, Developed ex-US, and Emerging — over the
 * common period the international series allow (they start 1990-07). These are
 * the genuinely CAPM-consistent, diversified-equity classes for the risk-return
 * scatter's "since 1990" set. Monthly stats are annualized (mean ×12, vol ×√12).
 *
 * Source CSVs live in data/sources/french/ (download from the French Data
 * Library). Run:  npm run data:global-equity
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { parseFrench, toColumns } from "./lib/parse-french.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "data", "sources", "french");
const OUT = join(root, "src", "data", "generated", "global-equity.ts");

const FILES = {
  us: "F-F_Research_Data_5_Factors_2x3.csv",
  devExUs: "Developed_ex_US_5_Factors.csv",
  emerging: "Emerging_5_Factors.csv",
};

/** Month (YYYYMM) → decimal market total return, from the monthly Mkt-RF+RF block. */
function monthlyMarket(file) {
  const blocks = parseFrench(readFileSync(join(srcDir, file), "utf8"));
  const m = blocks.find((b) => b.columns.includes("Mkt-RF") && b.rows[0]?.period.length === 6);
  if (!m) throw new Error(`No monthly market block in ${file}`);
  const { period, series } = toColumns(m);
  const out = new Map();
  for (let i = 0; i < period.length; i++) {
    const mkt = series["Mkt-RF"][i];
    const rf = series["RF"][i];
    if (mkt === null || rf === null) continue;
    out.set(period[i], (mkt + rf) / 100); // percent → decimal
  }
  return out;
}

const series = Object.fromEntries(Object.entries(FILES).map(([k, f]) => [k, monthlyMarket(f)]));

// Common period = the months present in all three series (apples-to-apples).
let periods = null;
for (const s of Object.values(series)) {
  const keys = new Set(s.keys());
  periods = periods === null ? keys : new Set([...periods].filter((p) => keys.has(p)));
}
const common = [...periods].sort();
const start = common[0];
const end = common[common.length - 1];

function stats(map) {
  const xs = common.map((p) => map.get(p));
  const n = xs.length;
  const mean = xs.reduce((s, x) => s + x, 0) / n;
  const varr = xs.reduce((s, x) => s + (x - mean) ** 2, 0) / (n - 1);
  const sd = Math.sqrt(varr);
  return { mu: Math.round(mean * 12 * 1e4) / 1e4, sigma: Math.round(sd * Math.sqrt(12) * 1e4) / 1e4 };
}

const assets = Object.fromEntries(Object.entries(series).map(([k, m]) => [k, stats(m)]));
const fmtYm = (p) => `${p.slice(0, 4)}-${p.slice(4, 6)}`;

// Aligned monthly total-return series (decimal, 6dp) for the rolling-returns tool.
const r6 = (x) => Math.round(x * 1e6) / 1e6;
const monthly = {
  dates: common.map(fmtYm),
  us: common.map((p) => r6(series.us.get(p))),
  devExUs: common.map((p) => r6(series.devExUs.get(p))),
  emerging: common.map((p) => r6(series.emerging.get(p))),
};

const body = `// AUTO-GENERATED by scripts/reduce-global-equity.mjs — DO NOT EDIT.
// Re-run: npm run data:global-equity
//
// Annualized NOMINAL market total return (Mkt-RF + RF) and volatility for broad,
// diversified equity by region, from the Fama–French regional 5-factor files.
// Monthly stats annualized (mean ×12, vol ×√12). A shorter, later window than the
// US-since-1928 series — the common period the international data allow.

export interface GlobalEquityStat { mu: number; sigma: number; }
export interface GlobalEquity {
  source: string;
  citation: string;
  span: [string, string];
  months: number;
  assets: { us: GlobalEquityStat; devExUs: GlobalEquityStat; emerging: GlobalEquityStat };
  /** Aligned monthly total returns (decimals) over the common period. */
  monthly: { dates: string[]; us: number[]; devExUs: number[]; emerging: number[] };
}

export const globalEquity: GlobalEquity = ${JSON.stringify(
  {
    source: "Kenneth R. French Data Library — regional 5-factor files (market total return = Mkt-RF + RF).",
    citation: "Fama, E. F., & French, K. R. — US, Developed ex-US, and Emerging market portfolios.",
    span: [fmtYm(start), fmtYm(end)],
    months: common.length,
    assets,
    monthly,
  },
  null,
  2,
)};
`;

writeFileSync(OUT, body);
console.log(`global-equity ${fmtYm(start)}..${fmtYm(end)} (${common.length} mo):`, assets);
