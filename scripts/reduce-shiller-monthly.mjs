/**
 * Reduce Shiller's ie_data.xls → src/data/generated/shiller-monthly.ts
 *
 * A monthly series of U.S. stock-market total returns (dividends reinvested, real
 * / inflation-adjusted) back to 1871, derived from Robert Shiller's "Real Total
 * Return Price" column. Monthly granularity is what powers two tools that annual
 * data can't:
 *   • Dollar-cost averaging vs. lump sum (spreading a windfall over months).
 *   • "Time in the market" — what missing the best months does to returns.
 *
 * Returns are month-over-month changes in the real total-return index, so they're
 * inflation-adjusted. Run:  npm run data:shiller-monthly
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readWorkbook } from "./lib/read-xlsx.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "data", "sources", "shiller", "ie_data.xls");
const OUT = join(root, "src", "data", "generated", "shiller-monthly.ts");

const COL_DATE = 0;
const COL_PRICE = 1;
const COL_TR = 9; // Real Total Return Price (dividends reinvested, real)

function main() {
  const rows = readWorkbook(SRC).sheet("Data");

  const pts = []; // { year, month, tr }
  for (const r of rows) {
    const dateCell = r?.[COL_DATE];
    const price = r?.[COL_PRICE];
    const tr = r?.[COL_TR];
    if (typeof dateCell !== "number" || dateCell < 1800 || dateCell > 2100) continue;
    if (typeof price !== "number" || typeof tr !== "number" || tr <= 0) continue;
    // Shiller encodes dates as YYYY.MM decimals (1871.01 = Jan, 1871.1 = Oct):
    // month = fractional part × 100; +1e-6 guards float error in the floor.
    const year = Math.floor(dateCell + 1e-6);
    const month = Math.round((dateCell - year) * 100);
    if (month < 1 || month > 12) continue;
    pts.push({ year, month, tr });
  }

  // Month-over-month real total returns.
  const returns = [];
  for (let i = 1; i < pts.length; i++) returns.push(pts[i].tr / pts[i - 1].tr - 1);
  const start = pts[1]; // first return is dated to the second observation
  const end = pts[pts.length - 1];

  // Sanity: annualized real total return over the whole span.
  const growth = pts[pts.length - 1].tr / pts[0].tr;
  const yrs = (pts.length - 1) / 12;
  const cagr = Math.pow(growth, 1 / yrs) - 1;

  const out = {
    source: "Robert J. Shiller, Irrational Exuberance data (ie_data.xls), Yale University.",
    citation: "Shiller, R. J. — monthly S&P Composite Real Total Return Price.",
    real: true,
    startYear: start.year,
    startMonth: start.month,
    endYear: end.year,
    endMonth: end.month,
    returns: returns.map((x) => Math.round(x * 1e6) / 1e6),
  };
  writeFileSync(OUT, render(out));

  console.log(
    `shiller-monthly: ${returns.length} monthly real total returns, ` +
      `${start.year}.${String(start.month).padStart(2, "0")}–${end.year}.${String(end.month).padStart(2, "0")}\n` +
      `  long-run real total return ≈ ${(cagr * 100).toFixed(2)}%/yr\n  → ${OUT}`
  );
}

function render(o) {
  // Chunk the returns array so the generated line isn't absurdly long.
  const nums = o.returns.map(String);
  const lines = [];
  for (let i = 0; i < nums.length; i += 12) lines.push("    " + nums.slice(i, i + 12).join(", ") + ",");

  return `// AUTO-GENERATED by scripts/reduce-shiller-monthly.mjs — DO NOT EDIT.
// Re-run: npm run data:shiller-monthly
//
// Monthly U.S. stock-market total returns (dividends reinvested, REAL /
// inflation-adjusted), from Robert Shiller's ie_data.xls. \`returns[i]\` is the
// real total return for the (i+1)-th month starting at { startYear, startMonth }.

export interface ShillerMonthly {
  source: string;
  citation: string;
  /** Returns are inflation-adjusted (real). */
  real: boolean;
  startYear: number;
  startMonth: number;
  endYear: number;
  endMonth: number;
  /** Month-over-month real total returns (decimals), consecutive from the start. */
  returns: number[];
}

export const shillerMonthly: ShillerMonthly = {
  source: ${JSON.stringify(o.source)},
  citation: ${JSON.stringify(o.citation)},
  real: ${o.real},
  startYear: ${o.startYear},
  startMonth: ${o.startMonth},
  endYear: ${o.endYear},
  endMonth: ${o.endMonth},
  returns: [
${lines.join("\n")}
  ],
};
`;
}

main();
