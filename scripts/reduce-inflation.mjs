/**
 * Reduce FRED CPI category series → src/data/generated/inflation.ts
 *
 * The data behind "What happened to your dollar?": the annual price level of the
 * overall CPI plus a spread of everyday categories, so a reader can rebase to any
 * year and watch how differently prices moved — college and medical care soaring,
 * toys and clothing flat or falling. Everyday data most people never actually see.
 *
 * Monthly FRED series → annual averages. We also record the common year range
 * (where every category has data) so the tool's start-year slider stays valid.
 *
 * Run:  npm run data:inflation
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { parseFred } from "./lib/parse-fred.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const FRED = join(root, "data", "sources", "fred");
const OUT = join(root, "src", "data", "generated", "inflation.ts");

const CATEGORIES = [
  { id: "CPIAUCSL", name: "All items", baseline: true },
  { id: "CUUR0000SEEB", name: "College tuition" },
  { id: "CPIMEDSL", name: "Medical care" },
  { id: "CUSR0000SAH1", name: "Shelter" },
  { id: "CPIFABSL", name: "Food & drink" },
  { id: "CPIENGSL", name: "Energy" },
  { id: "CUUR0000SETA01", name: "New cars" },
  { id: "CPIAPPSL", name: "Clothing" },
  { id: "CUUR0000SERE01", name: "Toys & games" },
];

const round = (x, dp) => Math.round(x * 10 ** dp) / 10 ** dp;

/** Monthly rows → { year: annual mean } (years with ≥6 observed months). */
function annualize(rows) {
  const byYear = new Map();
  for (const r of rows) {
    if (r.value === null) continue;
    const y = +r.date.slice(0, 4);
    if (!byYear.has(y)) byYear.set(y, []);
    byYear.get(y).push(r.value);
  }
  const out = [];
  for (const [year, vals] of [...byYear.entries()].sort((a, b) => a[0] - b[0])) {
    if (vals.length >= 6) out.push({ year, index: round(vals.reduce((s, v) => s + v, 0) / vals.length, 3) });
  }
  return out;
}

function main() {
  const categories = CATEGORIES.map((c) => {
    const { rows } = parseFred(join(FRED, `${c.id}.csv`));
    return { ...c, series: annualize(rows) };
  });

  const commonStart = Math.max(...categories.map((c) => c.series[0].year));
  const commonEnd = Math.min(...categories.map((c) => c.series[c.series.length - 1].year));

  const out = {
    asOf: commonEnd,
    source: "U.S. Bureau of Labor Statistics via FRED (Federal Reserve Bank of St. Louis).",
    commonStart,
    commonEnd,
    categories,
  };
  writeFileSync(OUT, render(out));

  // Quick narrative sanity: rebased multiples from commonStart to commonEnd.
  const at = (c, y) => c.series.find((p) => p.year === y)?.index;
  const mult = (c) => at(c, commonEnd) / at(c, commonStart);
  const sorted = [...categories].filter((c) => !c.baseline).sort((a, b) => mult(b) - mult(a));
  console.log(
    `inflation: ${categories.length} categories, common range ${commonStart}–${commonEnd}\n` +
      `  fastest riser: ${sorted[0].name} ×${mult(sorted[0]).toFixed(1)}   ` +
      `slowest: ${sorted[sorted.length - 1].name} ×${mult(sorted[sorted.length - 1]).toFixed(1)}\n` +
      `  all items ×${mult({ series: categories[0].series }).toFixed(1)}\n  → ${OUT}`
  );
}

function render(o) {
  const cats = o.categories
    .map((c) => {
      const s = c.series.map((p) => `{ year: ${p.year}, index: ${p.index} }`).join(", ");
      return `  { id: ${JSON.stringify(c.id)}, name: ${JSON.stringify(c.name)}${c.baseline ? ", baseline: true" : ""}, series: [${s}] },`;
    })
    .join("\n");
  return `// AUTO-GENERATED by scripts/reduce-inflation.mjs — DO NOT EDIT.
// Re-run: npm run data:inflation
//
// Annual CPI price levels for everyday categories (US BLS via FRED). Index values
// are on each series' own base; the tool rebases them to a chosen start year.

export interface CpiPoint { year: number; index: number; }
export interface CpiCategory {
  id: string;
  name: string;
  /** True for the headline "All items" CPI. */
  baseline?: boolean;
  series: CpiPoint[];
}

export interface InflationData {
  asOf: number;
  source: string;
  /** First / last year every category has data (valid slider range). */
  commonStart: number;
  commonEnd: number;
  categories: CpiCategory[];
}

export const inflation: InflationData = {
  asOf: ${o.asOf},
  source: ${JSON.stringify(o.source)},
  commonStart: ${o.commonStart},
  commonEnd: ${o.commonEnd},
  categories: [
${cats}
  ],
};
`;
}

main();
