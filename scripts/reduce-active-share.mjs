/**
 * Reduce Antti Petajisto's Active Share data → src/data/generated/active-share.ts
 *
 * Active Share (Cremers & Petajisto 2009) is the fraction of a fund's holdings
 * that differ from its benchmark index: ~0% = a closet indexer that hugs the
 * index while charging active fees, ~100% = a genuine stock-picker. This reducer
 * turns the fund-quarter panel into a small, shippable aggregate: the asset-
 * weighted average Active Share by year, and the share of fund assets sitting in
 * "closet indexers" (Active Share below 60%, Petajisto's threshold), which shows
 * how closet indexing rose over the 1990s–2000s.
 *
 * The raw file (data/sources/PETAJISTO/) is LICENSED and git-ignored — only this
 * reduced, attributed aggregate ships. Run:  npm run data:active-share
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "data", "sources", "PETAJISTO", "active share", "activeshare.csv");
const OUT = join(root, "src", "data", "generated", "active-share.ts");

// Petajisto's closet-indexer threshold: Active Share below 0.60.
const CLOSET_MAX = 0.6;
// Histogram buckets over [0,1].
const BUCKETS = [
  [0.0, 0.2],
  [0.2, 0.4],
  [0.4, 0.6],
  [0.6, 0.8],
  [0.8, 1.01],
];

const lines = readFileSync(SRC, "utf8").split(/\r?\n/);
const header = lines[0].split(",");
const I = {
  rdate: header.indexOf("rdate"),
  as: header.indexOf("activeshare"),
  indexfund: header.indexOf("indexfund"),
  tna: header.indexOf("tna"),
};

// year → { wSum, wAsSum, closetAssets, activeAssets(non-index total), nRows, buckets[] }
const years = new Map();
let end = "";

for (let i = 1; i < lines.length; i++) {
  const row = lines[i];
  if (!row) continue;
  // fund_name (last column) can contain commas, but every field we read sits
  // before it, so a plain split is safe for these indices.
  const f = row.split(",");
  const isIndex = f[I.indexfund] === "1";
  if (isIndex) continue; // closet-indexing is about ACTIVE funds' behaviour
  const as = Number(f[I.as]);
  const tna = Number(f[I.tna]);
  if (!Number.isFinite(as) || !Number.isFinite(tna) || tna <= 0 || as < 0) continue;
  const ymd = f[I.rdate]; // YYYY/MM/DD
  const year = Number(ymd.slice(0, 4));
  if (!Number.isFinite(year)) continue;
  if (ymd > end) end = ymd;

  let y = years.get(year);
  if (!y) {
    y = { assets: 0, wAs: 0, closetAssets: 0, nRows: 0, buckets: BUCKETS.map(() => 0) };
    years.set(year, y);
  }
  y.assets += tna;
  y.wAs += as * tna;
  if (as < CLOSET_MAX) y.closetAssets += tna;
  y.nRows += 1;
  const b = BUCKETS.findIndex(([lo, hi]) => as >= lo && as < hi);
  if (b >= 0) y.buckets[b] += tna;
}

const r3 = (x) => Math.round(x * 1000) / 1000;
const sortedYears = [...years.keys()].sort((a, b) => a - b);

const byYear = sortedYears.map((year) => {
  const y = years.get(year);
  return {
    year,
    meanActiveShare: r3(y.wAs / y.assets), // asset-weighted
    closetShare: r3(y.closetAssets / y.assets), // asset share in closet indexers
    funds: y.nRows, // fund-quarter observations that year
  };
});

// Asset-weighted distribution for the most recent full year in the file.
const latestYear = sortedYears[sortedYears.length - 1];
const ly = years.get(latestYear);
const distribution = BUCKETS.map(([lo, hi], i) => ({
  label: `${Math.round(lo * 100)}–${Math.round(Math.min(hi, 1) * 100)}%`,
  share: r3(ly.buckets[i] / ly.assets),
}));

const body = `// AUTO-GENERATED by scripts/reduce-active-share.mjs — DO NOT EDIT.
// Re-run: npm run data:active-share
//
// Active Share (Cremers & Petajisto 2009): the fraction of a fund's holdings that
// differ from its benchmark. This is the asset-weighted average across US equity
// mutual funds by year, plus the share of assets in "closet indexers" (Active
// Share < 60%). Index funds are excluded. Derived from Antti Petajisto's Active
// Share dataset; the raw file is licensed and not redistributed.

export interface ActiveShareYear {
  year: number;
  /** Asset-weighted mean Active Share (0–1) across active US equity funds. */
  meanActiveShare: number;
  /** Share of active-fund assets in closet indexers (Active Share < 0.60). */
  closetShare: number;
  /** Fund-quarter observations behind the year. */
  funds: number;
}
export interface ActiveShareData {
  source: string;
  citation: string;
  span: [number, number];
  closetThreshold: number;
  byYear: ActiveShareYear[];
  /** Asset-weighted Active Share distribution for the most recent year. */
  latestYear: number;
  distribution: { label: string; share: number }[];
}

export const activeShare: ActiveShareData = ${JSON.stringify(
  {
    source: "Antti Petajisto, Active Share dataset (US equity mutual funds).",
    citation:
      "Cremers, M., & Petajisto, A. (2009). How Active Is Your Fund Manager? A New Measure That Predicts Performance. Review of Financial Studies 22(9).",
    span: [sortedYears[0], latestYear],
    closetThreshold: CLOSET_MAX,
    byYear,
    latestYear,
    distribution,
  },
  null,
  2,
)};
`;

writeFileSync(OUT, body);
console.log(
  `Wrote ${OUT}\n  years ${sortedYears[0]}–${latestYear}, ${byYear.length} points; ` +
    `latest mean AS ${byYear[byYear.length - 1].meanActiveShare}, ` +
    `closet share ${byYear[byYear.length - 1].closetShare}; end ${end}`,
);
